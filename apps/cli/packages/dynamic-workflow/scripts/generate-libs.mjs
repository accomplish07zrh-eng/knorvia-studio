// Embeds TypeScript stdlib declarations for dynamic workflow compilation.

import { existsSync } from "node:fs";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT_ENTRY_LIBRARY = "lib.es2022.d.ts";
const LIB_REFERENCE_REGEX = /^\/\/\/\s*<reference\s+lib=["']([^"']+)["']\s*\/>/gm;

async function discoverTypeScriptEnvironment(searchOrigin) {
  const specifier = "typescript/package.json";
  const resolvedUrl = import.meta.resolve(specifier, searchOrigin);
  const pkgJsonPath = fileURLToPath(resolvedUrl);
  const pkgContent = await readFile(pkgJsonPath, "utf8");
  const parsed = JSON.parse(pkgContent);

  const libDirPath = resolve(dirname(pkgJsonPath), "lib");
  return {
    version: parsed.version,
    libDir: libDirPath,
  };
}

async function isOutputCurrent(targetFilePath, expectedVersion) {
  if (!existsSync(targetFilePath)) {
    return false;
  }
  try {
    const existingContent = await readFile(targetFilePath, "utf8");
    const marker = `export const TS_LIB_VERSION = ${JSON.stringify(expectedVersion)};`;
    return existingContent.includes(marker);
  } catch {
    return false;
  }
}

function extractDirectives(content) {
  const referenced = [];
  const matches = content.matchAll(LIB_REFERENCE_REGEX);
  for (const m of matches) {
    const libName = m[1];
    referenced.push(`lib.${libName}.d.ts`);
  }
  return referenced;
}

async function collectStandardLibraryClosure(directory, entryName) {
  const closure = new Map();
  const pending = [entryName];

  while (pending.length > 0) {
    const current = pending.shift();
    if (closure.has(current)) {
      continue;
    }

    const fullPath = join(directory, current);
    const text = await readFile(fullPath, "utf8");
    closure.set(current, text);

    const childNames = extractDirectives(text);
    for (const child of childNames) {
      if (!closure.has(child)) {
        pending.push(child);
      }
    }
  }

  return closure;
}

function synthesizeSourceFile(tsVersion, libMap) {
  const sortedKeys = Array.from(libMap.keys()).sort();
  const lines = [
    "// GENERATED FILE — DO NOT EDIT.",
    "// Regenerated by scripts/generate-libs.mjs whenever the installed typescript",
    "// version changes. Embeds the TypeScript stdlib .d.ts closure so the workflow",
    "// compiler host is fully virtual (no disk access in the bundled/SEA CLI).",
    `export const TS_LIB_VERSION = ${JSON.stringify(tsVersion)};`,
    "",
    "export const TS_LIBS: Record<string, string> = {",
  ];

  for (const key of sortedKeys) {
    const val = libMap.get(key);
    lines.push(`  ${JSON.stringify(key)}: ${JSON.stringify(val)},`);
  }

  lines.push("};", "");
  return lines.join("\n");
}

async function main() {
  const scriptLocation = fileURLToPath(import.meta.url);
  const pkgRoot = resolve(dirname(scriptLocation), "..");
  const destinationFile = join(pkgRoot, "src", "compiler", "libs.generated.ts");

  const tsEnv = await discoverTypeScriptEnvironment(import.meta.url);
  const alreadyUpToDate = await isOutputCurrent(destinationFile, tsEnv.version);
  if (alreadyUpToDate) {
    process.exit(0);
  }

  const libMap = await collectStandardLibraryClosure(tsEnv.libDir, ROOT_ENTRY_LIBRARY);
  const generatedCode = synthesizeSourceFile(tsEnv.version, libMap);

  await writeFile(destinationFile, generatedCode, "utf8");
  process.stdout.write(
    `generate-libs: wrote ${libMap.size} lib files for typescript@${tsEnv.version}\n`,
  );
}

await main();
